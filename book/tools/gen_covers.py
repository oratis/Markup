def load_prompts(outdir):
    """优先读产出目录里的 cover_prompts.json，没有就用内置的《要有光》那套。"""
    p = f"{outdir}/meta/cover_prompts.json"
    if os.path.exists(p):
        d = json.load(open(p, encoding="utf-8"))
        return d["style"], [(int(k), v) for k, v in sorted(
            d["subjects"].items(), key=lambda kv: int(kv[0]))]
    return STYLE, SUBJECTS


def gen(seq, subject, outdir, slug, style):
    dst = f"{outdir}/covers/{slug}.jpg"
    if os.path.exists(dst) and os.path.getsize(dst) > 10000:
        return seq, "已存在", dst
    payload = json.dumps({
        "model": MODEL,
        "prompt": f"{subject}。{style}",
        "sequential_image_generation": "disabled",
        "response_format": "url",
        "size": SIZE,
        "stream": False,
        "watermark": False,
    }).encode()
    req = urllib.request.Request(API, data=payload, headers={
        "Content-Type": "application/json", "Authorization": f"Bearer {KEY}"})
    for attempt in range(4):
        try:
            with urllib.request.urlopen(req, timeout=180) as r:
                data = json.load(r)
            url = data["data"][0]["url"]
            urllib.request.urlretrieve(url, dst)
            return seq, "OK", dst
        except Exception as e:
            if attempt == 3:
                return seq, f"失败 {e}", ""
            time.sleep(4 * (attempt + 1))


def main():
    if len(sys.argv) < 2:
        raise SystemExit("用法：gen_covers.py <产出目录> [序号...]")
    outdir = sys.argv[1].rstrip("/")
    only = {int(x) for x in sys.argv[2:]} if len(sys.argv) > 2 else None
    os.makedirs(f"{outdir}/covers", exist_ok=True)
    index = json.load(open(f"{outdir}/meta/index.json", encoding="utf-8"))
    slugs = {m["seq"]: m["cover"].split("/")[-1][:-4] for m in index}

    style, subjects = load_prompts(outdir)
    jobs = [(s, t) for s, t in subjects if only is None or s in only]
    missing = [s for s, _ in jobs if s not in slugs]
    if missing:
        raise SystemExit(f"提示词里有 index.json 没有的序号：{missing}")
    with ThreadPoolExecutor(max_workers=4) as ex:
        for seq, status, path in ex.map(
                lambda j: gen(j[0], j[1], outdir, slugs[j[0]], style), jobs):
            size = os.path.getsize(path) if path and os.path.exists(path) else 0
            print(f"{seq:>2}  {status:<8} {size/1024:>7.0f} KB  {os.path.basename(path)}")


if __name__ == "__main__":
    main()
